-- 스펙 §6.4 "임시 비밀번호에는 만료 시간을 둔다" 구현.
--
-- 관리자가 발급한 임시 비밀번호는 지금까지 영구히 유효했다. 발급한 관리자는 그 값을
-- 알고 있으므로, 당사자가 쓰지 않고 방치하면 몇 달 뒤에도 그 계정으로 로그인해
-- 비밀번호를 바꿔 계정을 인수할 수 있다(대상이 Alert 수신자면 특보 승인 권한까지).
-- must_change_password 게이트는 API 접근만 막고 로그인과 비밀번호 변경은 허용한다.
--
-- 기존 파일(0009_auth_local.sql)을 고치지 않고 새 파일로 더한다 — 이미 적용된
-- 데이터베이스와 어긋나지 않게 하는 것이 이 폴더의 규칙이다.
--
-- null은 "만료 없음"이다. 이 마이그레이션 이전에 발급된 임시 비밀번호가 그 상태로
-- 남는데, 그것을 여기서 일괄로 만료시키지는 않는다: 지금 그 값으로만 로그인할 수
-- 있는 사람을 갑자기 잠그는 쪽이 더 나쁘다. 새로 발급되는 것부터 만료가 붙는다.
begin;

alter table auth_accounts add column if not exists temp_password_expires_at timestamptz;

commit;
