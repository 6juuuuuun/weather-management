-- 카카오워크를 걷어내고 발송 채널을 SMS(LMS)로 바꾼다.
--
-- 발송 주소가 `employees.kakaowork_user_id`(이메일 조회로 채우던 값)에서
-- `employees.phone`(번호 자체가 주소)으로 바뀌었다. 조회·재연결·수동 입력이
-- 모두 사라졌으므로 이 컬럼을 채울 수 있는 경로가 시스템에 하나도 남아 있지
-- 않고, 남아 있는 값도 카카오워크 없이는 아무 뜻이 없다.
--
-- **남겨 두지 않는 이유**: 쓰이지 않는 컬럼은 다음 사람의 시간을 먹는다.
-- "이건 뭐지, 왜 비어 있지, 채워야 하나"를 한 번씩 묻게 되고, 그보다 나쁘게는
-- 누군가 이 값을 다시 보는 질의를 만들어 낼 수 있다. 값이 필요하면 git 기록에
-- 남아 있다(이 마이그레이션 직전 커밋).
alter table employees drop column if exists kakaowork_user_id;

-- dispatches.channel의 기본값도 함께 고친다.
--
-- 이 컬럼은 "그 회차가 **실제로 어디로** 나갔는가"를 적는 자리다(QA W-29). 기본값이
-- 'kakaowork'로 남아 있으면, 앞으로 무슨 일이 있어도 존재하지 않는 채널 이름이
-- 이력에 박힌다 — 나중에 이력을 되짚는 사람이 "그때는 카카오워크로 보냈구나"라고
-- 읽는다. 지금 실제로 나가는 곳은 앱 로그뿐이므로 기본값도 'log'다.
--
-- 앱 코드(jobs/send.ts·jobs/weatherTick.ts)는 언제나 이 값을 명시해 넣으므로
-- 기본값이 실제로 쓰이는 경로는 없다. 그래도 고쳐 둔다: 기본값은 "아무도 말해
-- 주지 않을 때 무엇이 참인가"에 대한 스키마의 답이고, 거짓말로 남겨 둘 이유가 없다.
alter table dispatches alter column channel set default 'log';
