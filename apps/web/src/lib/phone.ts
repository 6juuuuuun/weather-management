// 휴대폰 번호 입력 서식. 가입 화면(pages/Signup.tsx)과 직원 관리 화면
// (pages/Employees.tsx)이 같은 모양으로 보여야 해서 한 곳에 둔다.
//
// 서버의 최종 관문은 server/src/phone.ts다 — 여기서 하는 일은 **거절이 아니라
// 서식**이다. 화면은 방벽이 될 수 없으므로(브라우저를 거치지 않는 요청이 있다)
// 규칙을 두 벌로 나눠 적지 않는다: 여기서는 숫자만 남겨 하이픈을 넣어 주고,
// "이 번호가 유효한가"는 서버가 판정해 문구까지 돌려준다. 그래야 두 판정이
// 갈라져 화면은 통과시키고 서버만 거절하는(또는 그 반대의) 상태가 생기지 않는다.
//
// 붙여넣기도 이 함수를 그대로 지난다 — `01012345678`도 `010 1234 5678`도
// onChange 한 번에 `010-1234-5678`이 된다.

/**
 * 입력값에서 숫자만 남겨 하이픈을 끼운다. 11자리를 넘는 숫자는 버린다
 * (휴대폰 번호는 최대 11자리다 — server/src/phone.ts).
 *   10자리: 3-3-4 · 11자리: 3-4-4
 * 입력 도중에는 아직 자릿수가 모자라므로 앞에서부터 채워 나간다.
 */
export function formatPhoneInput(raw: string): string {
  const d = raw.replace(/\D/g, "").slice(0, 11);
  if (d.length <= 3) return d;
  if (d.length <= 7) return `${d.slice(0, 3)}-${d.slice(3)}`;
  // 8~10자리는 3-3-N, 11자리가 되는 순간 3-4-4로 다시 묶인다.
  const mid = d.length === 11 ? 4 : 3;
  return `${d.slice(0, 3)}-${d.slice(3, 3 + mid)}-${d.slice(3 + mid)}`;
}

// 정규형("010-1234-5678")의 최대 길이. input의 maxLength에 쓴다 — 서식이 이미
// 11자리에서 자르지만, 붙여넣기 시 브라우저가 잘라 주는 편이 덜 놀랍다.
export const PHONE_MAX_LENGTH = 13;
